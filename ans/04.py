"""
問題4: 関数とデフォルト引数
===========================

次のコードを実行したとき，それぞれの行は何を出力するか答えよ．
"""


def power(base, exp=2):
    return base ** exp


print(power(3))               # ①
print(power(3, 4))            # ②
print(power(exp=3, base=2))   # ③


# ---- 解答 ----
# ① 9    (3の2乗．exp はデフォルト値の 2 が使われる)
# ② 81   (3の4乗)
# ③ 8    (キーワード引数で順序を入れ替えて指定．2の3乗)
#
# 解説:
#   デフォルト引数を持つ関数では，省略すればデフォルト値が使われる．
#   呼び出し時に「引数名=値」の形 (キーワード引数) で渡せば，
#   定義順と関係なく指定できる．
